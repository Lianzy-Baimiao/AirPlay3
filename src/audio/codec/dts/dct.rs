fn clp(v: &mut [i32]) {
    v.iter_mut().for_each(|x| *x = clip23(*x));
}

/// 输入很大时先缩小 4 倍，返回移位数
fn prescale(input: &[i32], a: &mut [i32]) -> u32 {
    let mag = input.iter().fold(0i32, |m, &x| m.wrapping_add(x.wrapping_abs()));
    let shift = if mag > 0x40_0000 { 2 } else { 0 };
    let round = if shift > 0 { 1 << (shift - 1) } else { 0 };
    for (v, &x) in a.iter_mut().zip(input) {
        *v = x.wrapping_add(round) >> shift;
    }
    shift
}

fn finish(b: &mut [i32], shift: u32, out: &mut [i32]) {
    let n = b.len();
    for v in b.iter_mut() {
        *v = clip23(v.wrapping_shl(shift));
    }
    for i in 0..n / 2 {
        let k = n - 1 - i;
        out[i] = clip23(b[i].wrapping_sub(b[k]));
        out[n / 2 + i] = clip23(b[i].wrapping_add(b[k]));
    }
}

/// 32 点：32 个子带样本 → 32 个输出
pub(super) fn imdct_half_32(out: &mut [i32], input: &[i32]) {
    let (mut a, mut b) = ([0i32; 32], [0i32; 32]);
    let shift = prescale(&input[..32], &mut a);

    sum_a(&a, &mut b[..16], 16);
    sum_b(&a, &mut b[16..], 16);
    clp(&mut b);

    sum_a(&b, &mut a[..8], 8);
    sum_b(&b, &mut a[8..16], 8);
    sum_c(&b[16..], &mut a[16..24], 8);
    sum_d(&b[16..], &mut a[24..], 8);
    clp(&mut a);

    dct_a(&a[..8], &mut b[..8]);
    for k in (8..32).step_by(8) {
        dct_b(&a[k..k + 8], &mut b[k..k + 8]);
    }
    clp(&mut b);

    modulate(&MOD_A, &b[..16], &mut a[..16]);
    modulate_b(&MOD_B, &mut b[16..], &mut a[16..]);
    clp(&mut a);

    modulate(&MOD_C, &a, &mut b);
    finish(&mut b, shift, out);
}

/// 64 点：64 个子带样本 → 64 个输出
pub(super) fn imdct_half_64(out: &mut [i32], input: &[i32]) {
    let (mut a, mut b) = ([0i32; 64], [0i32; 64]);
    let shift = prescale(&input[..64], &mut a);

    sum_a(&a, &mut b[..32], 32);
    sum_b(&a, &mut b[32..], 32);
    clp(&mut b);

    sum_a(&b, &mut a[..16], 16);
    sum_b(&b, &mut a[16..32], 16);
    sum_c(&b[32..], &mut a[32..48], 16);
    sum_d(&b[32..], &mut a[48..], 16);
    clp(&mut a);

    sum_a(&a, &mut b[..8], 8);
    sum_b(&a, &mut b[8..16], 8);
    for k in (16..64).step_by(16) {
        sum_c(&a[k..], &mut b[k..k + 8], 8);
        sum_d(&a[k..], &mut b[k + 8..k + 16], 8);
    }
    clp(&mut b);

    dct_a(&b[..8], &mut a[..8]);
    for k in (8..64).step_by(8) {
        dct_b(&b[k..k + 8], &mut a[k..k + 8]);
    }
    clp(&mut a);

    modulate(&MOD_A, &a[..16], &mut b[..16]);
    for k in (16..64).step_by(16) {
        modulate_b(&MOD_B, &mut a[k..k + 16], &mut b[k..k + 16]);
    }
    clp(&mut b);

    modulate(&MOD64_A, &b[..32], &mut a[..32]);
    modulate_b(&MOD64_B, &mut b[32..], &mut a[32..]);
    clp(&mut a);

    modulate(&MOD64_C, &a, &mut b);
    finish(&mut b, shift, out);
}
