fn dct_a(i: &[i32], o: &mut [i32]) {
    for (v, row) in o.iter_mut().zip(&DCT_A) {
        *v = norm23(row.iter().zip(i).map(|(&c, &x)| c as i64 * x as i64).sum());
    }
}

fn dct_b(i: &[i32], o: &mut [i32]) {
    for (v, row) in o.iter_mut().zip(&DCT_B) {
        let r = ((i[0] as i64) << 23) + row.iter().zip(&i[1..]).map(|(&c, &x)| c as i64 * x as i64).sum::<i64>();
        *v = norm23(r);
    }
}

/// mod_a / mod_c / mod64_a / mod64_c：前一半乘和，后一半乘倒序的差
fn modulate(c: &[i32], i: &[i32], o: &mut [i32]) {
    let n = c.len();
    let h = n / 2;
    for k in 0..h {
        o[k] = mul23(c[k], i[k].wrapping_add(i[h + k]));
    }
    for m in h..n {
        let k = n - 1 - m;
        o[m] = mul23(c[m], i[k].wrapping_sub(i[h + k]));
    }
}

/// mod_b / mod64_b：先缩放后一半，再取和、倒序的差
fn modulate_b(c: &[i32], i: &mut [i32], o: &mut [i32]) {
    let h = c.len();
    for k in 0..h {
        i[h + k] = mul23(c[k], i[h + k]);
    }
    for k in 0..h {
        o[k] = i[k].wrapping_add(i[h + k]);
    }
    for (m, v) in o[h..2 * h].iter_mut().enumerate() {
        let k = h - 1 - m;
        *v = i[k].wrapping_sub(i[h + k]);
    }
}

