//! 定点的半长 IMDCT（32 / 64 子带合成滤波用）

use super::dsp::{clip23, mul23, norm23};

fn sum_a(i: &[i32], o: &mut [i32], len: usize) {
    for (k, v) in o[..len].iter_mut().enumerate() {
        *v = i[2 * k].wrapping_add(i[2 * k + 1]);
    }
}

fn sum_b(i: &[i32], o: &mut [i32], len: usize) {
    o[0] = i[0];
    for (k, v) in o[..len].iter_mut().enumerate().skip(1) {
        *v = i[2 * k].wrapping_add(i[2 * k - 1]);
    }
}

fn sum_c(i: &[i32], o: &mut [i32], len: usize) {
    for (k, v) in o[..len].iter_mut().enumerate() {
        *v = i[2 * k];
    }
}

fn sum_d(i: &[i32], o: &mut [i32], len: usize) {
    o[0] = i[1];
    for (k, v) in o[..len].iter_mut().enumerate().skip(1) {
        *v = i[2 * k - 1].wrapping_add(i[2 * k + 1]);
    }
}

