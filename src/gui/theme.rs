//! 「颜色透明」：整体颜色、焦点颜色、边框透明、透明雾化（与原版相同的四项，默认值也与原版相同）。
//!
//! 原版所有界面颜色都从「整体颜色」推出来：面板主体就是整体颜色，文字、悬停、分隔线等
//! 在它的基础上加 / 减一个灰度（暗色主题加、亮色主题减，以最亮的分量是否超过 0x80 区分），
//! 播放条和标题条的半透明玻璃按整体颜色的色相着色。这里按同样的规则推导。

