#[derive(Clone, Copy, PartialEq, Debug)]
pub struct Theme {
    pub body: [u8; 3],
    pub focus: [u8; 3],
    /// 边框（播放条、标题条的玻璃）的不透明度 0 ~ 255
    pub border_alpha: u8,
    pub frost: bool,
}

impl Default for Theme {
    fn default() -> Self {
        Theme { body: DEFAULT_BODY, focus: DEFAULT_FOCUS, border_alpha: 0, frost: false }
    }
}

impl Theme {
    pub fn from_settings(s: &crate::config::ThemeSettings) -> Theme {
        Theme { body: s.body, focus: s.focus, border_alpha: s.border_alpha, frost: s.frost }
    }
}

thread_local! {
    static CUR: Cell<Theme> = Cell::new(Theme::default());
}

/// 设置当前主题（界面线程）
pub fn set(t: Theme) {
    CUR.with(|c| c.set(t));
}

pub fn get() -> Theme {
    CUR.with(|c| c.get())
}

fn rgb(c: [u8; 3]) -> Rgba {
    Rgba(c[0], c[1], c[2], 255)
}

/// 面板主体的颜色（整体颜色）
pub fn body() -> Rgba {
    rgb(get().body)
}

/// 焦点颜色（当前播放的行、当前歌词、选中的分页……）
pub fn focus() -> Rgba {
    rgb(get().focus)
}

pub fn border_alpha() -> u8 {
    get().border_alpha
}

fn max3(c: Rgba) -> u8 {
    c.0.max(c.1).max(c.2)
}

/// 每个分量加上 d（饱和到 0 ~ 255）
fn add(c: Rgba, d: i32) -> Rgba {
    let f = |v: u8| (v as i32 + d).clamp(0, 255) as u8;
    Rgba(f(c.0), f(c.1), f(c.2), c.3)
}

/// 主体颜色是否是亮色（原版以最亮的分量是否达到 0x80 区分）
pub fn light() -> bool {
    max3(body()) >= 0x80
}

/// 默认主题（主体 #202020）下的灰度 v 在当前主题下的颜色：与主体的差值不变，亮色主题方向相反
pub fn g(v: u8) -> Rgba {
    let d = v as i32 - DEFAULT_BODY[0] as i32;
    add(body(), if light() { -d } else { d })
}

/// 同上，带不透明度
pub fn ga(v: u8, a: u8) -> Rgba {
    g(v).alpha(a)
}

/// 面板主体边缘的亮线：主体与白色 65 : 190 混合
pub fn edge() -> Rgba {
    let b = body();
    let f = |v: u8| (v as u32 + ((255 - v as u32) * 65 + 127) / 255) as u8;
    Rgba(f(b.0), f(b.1), f(b.2), 255)
}

/// 标题条与主体之间的暗线：主体 × 190 / 256
pub fn separator() -> Rgba {
    let b = body();
    let f = |v: u8| ((v as u32 * 190) >> 8) as u8;
    Rgba(f(b.0), f(b.1), f(b.2), 255)
}

/// 玻璃（灰度 v）按主体的色相着色：每个分量减去主体中它与最亮分量的差
pub fn tint(v: u8) -> (u8, u8, u8) {
    let b = body();
    let m = max3(b) as i32;
    let f = |c: u8| (v as i32 - (m - c as i32)).clamp(0, 255) as u8;
    (f(b.0), f(b.1), f(b.2))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 与原版实测的颜色一致（原版在不同整体颜色下的截图）
    #[test]
    fn derived_colors_match_original() {
        let cases: [([u8; 3], Rgba, Rgba, (u8, u8, u8)); 6] = [
            ([0x20, 0x20, 0x20], Rgba(0x59, 0x59, 0x59, 255), Rgba(0x17, 0x17, 0x17, 255), (0xA5, 0xA5, 0xA5)),
            ([0x10, 0x20, 0x40], Rgba(0x4D, 0x59, 0x71, 255), Rgba(0x0B, 0x17, 0x2F, 255), (0x75, 0x85, 0xA5)),
            ([0x80, 0x80, 0x80], Rgba(0xA0, 0xA0, 0xA0, 255), Rgba(0x5F, 0x5F, 0x5F, 255), (0xA5, 0xA5, 0xA5)),
            ([0xD0, 0xB0, 0xB0], Rgba(0xDC, 0xC4, 0xC4, 255), Rgba(0x9A, 0x82, 0x82, 255), (0xA5, 0x85, 0x85)),
            ([0xFF, 0xFF, 0xFF], Rgba(0xFF, 0xFF, 0xFF, 255), Rgba(0xBD, 0xBD, 0xBD, 255), (0xA5, 0xA5, 0xA5)),
            ([0x40, 0x10, 0x10], Rgba(0x71, 0x4D, 0x4D, 255), Rgba(0x2F, 0x0B, 0x0B, 255), (0xA5, 0x75, 0x75)),
        ];
        for (b, e, s, t) in cases {
            set(Theme { body: b, ..Theme::default() });
            assert_eq!((edge(), separator(), tint(0xA5)), (e, s, t), "整体颜色 {b:02x?}");
        }
        // 默认主题下 g() 不改变灰度；亮色主题方向相反
        set(Theme::default());
        assert_eq!(g(200), Rgba::gray(200));
        set(Theme { body: [0xD0, 0xD0, 0xD0], ..Theme::default() });
        assert_eq!(g(200), Rgba::gray(0xD0 - 168));
        set(Theme::default());
    }
}
