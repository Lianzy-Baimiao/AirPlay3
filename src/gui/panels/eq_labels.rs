//! 均衡器上的像素字标签：自己设计的 3×5 点阵字体，位置与原版相同。

pub const LABEL_GRAY: u8 = 78;

/// 3×5 点阵（每行 3 位，高位在左）
fn glyph(c: char) -> [u8; 5] {
    match c {
        '0' => [0b111, 0b101, 0b101, 0b101, 0b111],
        '1' => [0b010, 0b110, 0b010, 0b010, 0b111],
        '2' => [0b111, 0b001, 0b111, 0b100, 0b111],
        '3' => [0b111, 0b001, 0b111, 0b001, 0b111],
        '4' => [0b101, 0b101, 0b111, 0b001, 0b001],
        '5' => [0b111, 0b100, 0b111, 0b001, 0b111],
        '6' => [0b111, 0b100, 0b111, 0b101, 0b111],
        '8' => [0b111, 0b101, 0b111, 0b101, 0b111],
        'P' => [0b111, 0b101, 0b111, 0b100, 0b100],
        'R' => [0b110, 0b101, 0b110, 0b101, 0b101],
        'E' => [0b111, 0b100, 0b110, 0b100, 0b111],
        'A' => [0b010, 0b101, 0b111, 0b101, 0b101],
        'M' => [0b101, 0b111, 0b111, 0b101, 0b101],
        'K' => [0b101, 0b110, 0b100, 0b110, 0b101],
        'H' => [0b101, 0b101, 0b111, 0b101, 0b101],
        'z' => [0b000, 0b111, 0b010, 0b100, 0b111],
        'd' => [0b001, 0b001, 0b111, 0b101, 0b111],
        'B' => [0b110, 0b101, 0b110, 0b101, 0b110],
        '+' => [0b000, 0b010, 0b111, 0b010, 0b000],
        '-' => [0b000, 0b000, 0b111, 0b000, 0b000],
        _ => [0; 5],
    }
}

/// 一段文字的宽度（字宽 3、字距 1）
pub fn width(s: &str) -> i32 {
    (s.chars().count() as i32 * 4 - 1).max(0)
}

/// 画一段文字：左上角 (x, y)，每个点调用一次 `dot`
pub fn draw(s: &str, x: i32, y: i32, mut dot: impl FnMut(i32, i32)) {
    for (i, ch) in s.chars().enumerate() {
        for (dy, row) in glyph(ch).iter().enumerate() {
            for dx in 0..3 {
                if row & (0b100 >> dx) != 0 {
                    dot(x + i as i32 * 4 + dx, y + dy as i32);
                }
            }
        }
    }
}

